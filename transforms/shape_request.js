// Topic transform on psd-events: turns a raw event into the request the AI Inference transform sends to Gemini.
// Deterministic, so a throw here is a bug: it fails the publish and the poller records the failure.
function shapeRequest(message, metadata) {
  const raw = JSON.parse(message.data);
  const source = raw.source || (message.attributes && message.attributes.source);
  if (!SYSTEM[source]) {
    throw new Error("unknown source: " + source);
  }
  // Everything the tagged row needs travels inside the request, because the AI transform replaces the message data
  // and only echoes the request back as original_message.
  const carried = {
    event_id: raw.event_id,
    source: source,
    feed: raw.feed || null,
    guid: raw.guid || null,
    title: raw.title || null,
    url: raw.url || null,
    submitted_at: raw.published_at || null,
    text: String(raw.text || "").slice(0, 12000),
    screen_flagged: raw.screen && typeof raw.screen.flagged === "boolean" ? raw.screen.flagged : null,
  };
  message.data = JSON.stringify({
    model: MODEL,
    messages: [
      { role: "system", content: SYSTEM[source] },
      { role: "user", content: JSON.stringify(carried) },
    ],
    response_format: { type: "json_object" },
  });
  message.attributes = { source: source, event_id: String(raw.event_id || "") };
  return message;
}

