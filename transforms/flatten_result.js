// Subscription transform on psd-events-tag, after the AI Inference transform: turns {original_message, model_output}
// into the tagged row every consumer reads. It never throws: a model output that will not parse lands with tag_error set,
// so the notice shows as "extraction failed" instead of retrying a call that will not improve.
function flattenResult(message, metadata) {
  const out = JSON.parse(message.data);
  const request = requestOf(out.original_message);
  const carried = JSON.parse(request.messages[request.messages.length - 1].content);
  let x = {};
  let parseError = null;
  try {
    x = JSON.parse(stripFences(modelText(out.model_output)));
    if (x === null || typeof x !== "object" || Array.isArray(x)) {
      throw new Error("model output is not a JSON object");
    }
  } catch (e) {
    x = {};
    parseError = String(e).slice(0, 200);
  }
  const hazard = HAZARD_SET[x.hazard_type] ? x.hazard_type : "quality_only";
  const row = {
    event_id: carried.event_id,
    source: carried.source,
    feed: carried.feed,
    guid: carried.guid,
    title: carried.title,
    url: carried.url,
    store_id: null,
    submitted_at: carried.submitted_at,
    text: carried.text,
    product_name: [x.brand, x.product_name].filter(Boolean).join(" ") || carried.title,
    product_id: null,
    category: CATEGORY_SET[x.category] ? x.category : "other",
    hazard_type: hazard,
    severity: SEVERITY_BY_HAZARD[hazard],
    summary: x.summary || null,
    tag_confidence: typeof x.confidence === "number" ? x.confidence : null,
    model: MODEL_ID,
    tagged_at: new Date().toISOString(),
    recall_extract: JSON.stringify(x),
    label_payload: null,
    tag_error: parseError,
    screen_flagged: carried.screen_flagged,
  };
  message.data = JSON.stringify(row);
  message.attributes = {
    source: String(row.source || ""),
    severity: String(row.severity),
    hazard_type: row.hazard_type,
    event_id: String(row.event_id || ""),
  };
  return message;
}

// original_message is the request the topic transform built; accept it as an object, a JSON string, or a message
// whose data field holds it.
function requestOf(original) {
  let value = typeof original === "string" ? JSON.parse(original) : original;
  if (value && value.messages) {
    return value;
  }
  if (value && typeof value.data === "string") {
    return JSON.parse(value.data);
  }
  throw new Error("original_message holds no request");
}

// The Chat Completions shape first; the native Gemini shape as a fallback.
function modelText(output) {
  const value = typeof output === "string" ? JSON.parse(output) : output;
  if (value && value.choices && value.choices.length) {
    return value.choices[0].message.content;
  }
  if (value && value.candidates && value.candidates.length) {
    return value.candidates[0].content.parts.map(function (p) { return p.text || ""; }).join("");
  }
  throw new Error("model output has no choices or candidates");
}

function stripFences(text) {
  let s = String(text).trim();
  if (s.startsWith("```")) {
    s = s.replace(/^```[a-zA-Z]*\s*/, "").replace(/```\s*$/, "");
  }
  return s;
}

