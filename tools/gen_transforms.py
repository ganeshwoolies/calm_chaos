"""Renders the Pub/Sub transforms' generated constants from the knowledge bundle, and the gcloud transform files.

    uv run python tools/gen_transforms.py [--check] [--project PROJECT_ID]

The JavaScript transforms cannot read the bundle, so the closed lists, the severity by hazard and the model id are
written into their GENERATED blocks. --check writes nothing and exits 1 on drift. --project also writes
transforms/build/{topic,subscription}-transforms.yaml for gcloud; they name the project, so they stay out of git.
"""

import argparse
import json
import re
import sys
from pathlib import Path

import yaml

from app.agent import MODEL
from app.knowledge import REPO_DIR, load_bundle
from app.policy import Policy, build

TRANSFORMS = REPO_DIR / "transforms"
BUILD = TRANSFORMS / "build"
_BLOCK = re.compile(
    r"(// GENERATED by tools/gen_transforms\.py[^\n]*\n)(.*?)(// END GENERATED)",
    re.DOTALL,
)
# Temperature 0 for extraction; a generous token cap, because a thinking model spends part of it before answering.
INFERENCE_PARAMETERS = {"temperature": 0, "max_tokens": 4096}


def _js(value: object) -> str:
    return json.dumps(value, ensure_ascii=False)


def blocks(pol: Policy) -> dict[str, str]:
    hazards = [h.id for h in pol.taxonomy.hazard_types]
    ones = lambda names: "{ " + ", ".join(f"{n}: 1" for n in names) + " }"  # noqa: E731
    return {
        "shape_request.js": (
            f"const MODEL = {_js('google/' + MODEL)};\n"
            f"const CATEGORIES = {_js(', '.join(pol.taxonomy.categories))};\n"
            f"const HAZARDS = {_js(', '.join(hazards))};\n"
        ),
        "flatten_result.js": (
            f"const MODEL_ID = {_js(MODEL)};\n"
            f"const HAZARD_SET = {ones(hazards)};\n"
            f"const CATEGORY_SET = {ones(pol.taxonomy.categories)};\n"
            "const SEVERITY_BY_HAZARD = { "
            + ", ".join(
                f"{h}: {_js(s)}" for h, s in pol.recall.severity_by_hazard.items()
            )
            + " };\n"
        ),
    }


def render(path: Path, block: str) -> str:
    text = path.read_text(encoding="utf-8")
    rendered, count = _BLOCK.subn(lambda m: m.group(1) + block + m.group(3), text)
    if count != 1:
        raise SystemExit(f"{path.name}: expected one GENERATED block, found {count}")
    return rendered


class _Literal(yaml.SafeDumper):
    pass


_Literal.add_representer(
    str,
    lambda dumper, s: dumper.represent_scalar(
        "tag:yaml.org,2002:str", s, style="|" if "\n" in s else None
    ),
)


def gcloud_files(project: str) -> dict[Path, str]:
    shape = (TRANSFORMS / "shape_request.js").read_text(encoding="utf-8")
    flatten = (TRANSFORMS / "flatten_result.js").read_text(encoding="utf-8")
    topic = [{"javascriptUdf": {"code": shape, "functionName": "shapeRequest"}}]
    subscription = [
        {
            "aiInference": {
                # The global endpoint serves Gemini foundation models; this model has no us-central1 endpoint.
                "endpoint": f"projects/{project}/locations/global/publishers/google/models/{MODEL}",
                "unstructuredInference": {"parameters": INFERENCE_PARAMETERS},
            }
        },
        {"javascriptUdf": {"code": flatten, "functionName": "flattenResult"}},
    ]

    def dump(doc: list[dict]) -> str:
        return yaml.dump(doc, Dumper=_Literal, sort_keys=False, allow_unicode=True)

    return {
        BUILD / "topic-transforms.yaml": dump(topic),
        BUILD / "subscription-transforms.yaml": dump(subscription),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if a generated block is out of date",
    )
    parser.add_argument(
        "--project", help="also write the gcloud transform files for this project"
    )
    args = parser.parse_args()
    pol = build(load_bundle(REPO_DIR / "knowledge"), require_usable=False)
    drift = []
    for name, block in blocks(pol).items():
        path = TRANSFORMS / name
        rendered = render(path, block)
        if rendered == path.read_text(encoding="utf-8"):
            continue
        if args.check:
            drift.append(name)
        else:
            path.write_text(rendered, encoding="utf-8", newline="\n")
            print(f"wrote transforms/{name}")
    for name in drift:
        print(
            f"out of date: transforms/{name} (run uv run python tools/gen_transforms.py)"
        )
    if args.project and not args.check:
        BUILD.mkdir(exist_ok=True)
        for path, text in gcloud_files(args.project).items():
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {path.relative_to(REPO_DIR).as_posix()}")
    return 1 if drift else 0


if __name__ == "__main__":
    sys.exit(main())
