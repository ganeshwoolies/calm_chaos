"""Renders the skills' reference and asset files from the knowledge bundle.

A rule changes in one place: edit the concept in knowledge/, then run this. With --check, writes nothing and exits 1
when a generated file differs from what the bundle renders.

    uv run python tools/gen_skill_refs.py [--check]
"""

import argparse
import re
import sys
from collections.abc import Callable
from pathlib import Path

from app.knowledge import load_bundle
from app.policy import LABELS, RECALL, TAXONOMY, WARNING_HAZARDS, Policy, build

REPO_DIR = Path(__file__).resolve().parent.parent
SKILLS = REPO_DIR / "app" / "skills"
VENDOR_CASE = "/references/vendor-case-format.md"

_ACTIONS = {
    "hold": "hold the lot",
    "supplier_notice": "supplier notice",
    "qa_alert": "QA alert",
    "listing_check": "check the listing",
    "listing_fix": "listing fix",
}


def _header(*sources: str) -> str:
    return f"<!-- GENERATED by tools/gen_skill_refs.py from {', '.join(sources)}. Do not edit. -->\n\n"


def _minutes(value: int | None) -> str:
    return f"{value} min" if value else "none"


def severity_md(pol: Policy, bundle) -> str:
    hazards = "\n".join(
        f"| {h} | {s} |" for h, s in pol.recall.severity_by_hazard.items()
    )
    targets = "\n".join(
        f"| {sev} | {_minutes(t.customers_messaged)} | {_minutes(t.shelves_clear)} |"
        for sev in reversed(pol.severity_order)
        if (t := pol.recall.targets_minutes[sev])
    )
    reason = (
        "; dropping it needs a recorded reason"
        if pol.recall.checkout_block_drop_needs_reason
        else ""
    )
    return (
        _header(RECALL, TAXONOMY)
        + "# Recall severity and time targets\n\n"
        + "Severity follows the hazard type, never the notice's wording.\n\n"
        + "| Hazard type | Severity |\n|---|---|\n"
        + hazards
        + "\n\nTime targets, counted from the coordinator's approval:\n\n"
        + "| Severity | Customers messaged within | Shelves clear within |\n|---|---|---|\n"
        + targets
        + f"\n\nA checkout block is requested for {', '.join(pol.recall.checkout_block_severities)} recalls{reason}.\n"
        + f"A store is exposed when it holds the batch or received it within {pol.recall.exposure_days} days; "
        + f"online orders placed within {pol.recall.order_lookback_days} days are messaged.\n"
        + f"Exposed stores get a pull for {', '.join(pol.recall.store_action_severities)} recalls. For any other "
        + "severity no store action is proposed: the exposed stores are optional, and the coordinator adds the ones "
        + "to pull.\n"
    )


def label_rules_md(pol: Policy, bundle) -> str:
    rules = "\n".join(
        f"| {r.id} | {r.condition} | {r.severity or 'by warning, below'} | "
        f"{', '.join(_ACTIONS[a] for a in r.actions)} |"
        for r in pol.labels.rules
    )
    warnings = "\n".join(
        f"| {w.value} | {w.hazard_type} | {w.severity_missing_on_pack} |"
        for w in pol.warnings.warnings
    )
    default = pol.warnings.default
    targets = "\n".join(
        f"| {sev} | {_minutes(t.holds_verified)} | {_minutes(t.listing_fixed)} |"
        for sev in reversed(pol.severity_order)
        if (t := pol.labels.targets_minutes[sev])
    )
    return (
        _header(LABELS, WARNING_HAZARDS)
        + "# Label rules\n\n"
        + "Each finding's severity and actions come from its rule.\n\n"
        + "| Rule | When | Severity | Actions |\n|---|---|---|---|\n"
        + rules
        + "\n\nA warning missing from the pack:\n\n"
        + "| Warning | Hazard | Severity |\n|---|---|---|\n"
        + warnings
        + f"\n| any other warning | {default.hazard_type} | {default.severity_missing_on_pack} |"
        + "\n\nA hold covers every store holding the lot. Time targets, counted from the coordinator's approval:\n\n"
        + "| Severity | Holds verified within | Listing fixed within |\n|---|---|---|\n"
        + targets
        + "\n"
    )


def vendor_case_md(pol: Policy, bundle) -> str:
    concept = bundle.get(VENDOR_CASE)
    if concept is None:
        raise SystemExit(f"{VENDOR_CASE} is missing")
    body = re.sub(
        r"^\[\^[^\]]+\]:.*(?:\n[ \t]+.*)*\n?", "", concept.body, flags=re.MULTILINE
    )
    body = re.sub(r"\[\^[^\]]+\]", "", body).strip()
    return (
        _header(VENDOR_CASE)
        + f"# {concept.title}\n\n"
        + body.removeprefix("# Sections").strip()
        + "\n"
    )


OUTPUTS: dict[str, Callable[[Policy, object], str]] = {
    "recall-incident/references/severity.md": severity_md,
    "recall-incident/assets/vendor-case.md": vendor_case_md,
    "label-incident/references/label-rules.md": label_rules_md,
    "label-incident/assets/vendor-case.md": vendor_case_md,
}


def render_all(bundle_root: Path | None = None) -> dict[Path, str]:
    bundle = load_bundle(bundle_root)
    pol = build(bundle, require_usable=False)
    return {SKILLS / rel: render(pol, bundle) for rel, render in OUTPUTS.items()}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check", action="store_true", help="exit 1 if a generated file is out of date"
    )
    args = parser.parse_args()
    drift = []
    for path, text in render_all().items():
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == text:
            continue
        rel = path.relative_to(REPO_DIR).as_posix()
        if args.check:
            drift.append(rel)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {rel}")
    for rel in drift:
        print(f"out of date: {rel} (run uv run python tools/gen_skill_refs.py)")
    return 1 if drift else 0


if __name__ == "__main__":
    sys.exit(main())
