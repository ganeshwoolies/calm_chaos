from dataclasses import dataclass, field


@dataclass(frozen=True)
class ProductType:
    key: str
    category: str
    subcategory: str
    name: str  # "{variant}" is replaced by the variant
    variants: tuple[str, ...]
    sizes: tuple[str, ...]
    ingredients: str  # "{variant}" is replaced by the variant in lower case
    allergens: tuple[str, ...] = ()
    variant_allergens: dict[str, tuple[str, ...]] = field(default_factory=dict)
    warnings: tuple[str, ...] = ()
    variant_warnings: dict[str, tuple[str, ...]] = field(default_factory=dict)
    marks: tuple[str, ...] = ()
    shelf_life_days: int | None = None  # food only: production to best-before
    qty: tuple[int, int] = (6, 24)  # units per delivery
    price: tuple[float, float] = (2.0, 10.0)
    description: str = ""


