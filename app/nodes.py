REDRAFT_ATTEMPTS = 2
_HTML_COMMENT = re.compile(r"<!--.*?-->", re.DOTALL)
_GENERATED_FROM = re.compile(
    r"<!--\s*GENERATED by \S+ from (.*?)\.\s*Do not edit\.\s*-->", re.DOTALL
)
_CONCEPT_PATH = re.compile(r"/[\w./-]+\.md")

USAGE = (
    'Send an incident candidate as JSON, for example {"candidate_id": "recall:yoghurt_listeria", "kind": "recall"}. '
    "Fixture candidates are in data/fixtures/candidates."
)


def _text(text: str) -> Event:
    return Event(
        content=types.Content(role="model", parts=[types.Part.from_text(text=text)])
    )


def _input_text(node_input: Any) -> str:
    if isinstance(node_input, types.Content):
        return "".join(p.text or "" for p in node_input.parts or [])
    if isinstance(node_input, (dict, list)):
        return json.dumps(node_input)
    return str(node_input or "")


def parse_candidate(node_input: Any):
    """Accepts the push endpoint's {"data": ..., "attributes": ...} text or a bare JSON candidate."""
    try:
        payload = json.loads(_input_text(node_input).strip())
        if isinstance(payload, dict) and "data" in payload:
            payload = payload["data"]
        if isinstance(payload, str):
            payload = json.loads(payload)
        candidate = Candidate.model_validate(payload)
    except (ValueError, TypeError):
        yield _text(f"That is not an incident candidate. {USAGE}")
        yield Event(output={"status": "not_a_candidate"}, route="stop")
        return
    yield Event(
        output=candidate.model_dump(),
        route="candidate",
        state={"candidate": candidate.model_dump()},
    )


_NOT_RUN = {
    "in_progress": "is being drafted by another run",
    "duplicate": "is already handled",
    "suppressed": "was dismissed recently and is not raised again yet",
    "blocked": "was blocked by Model Armor screening",
}


def gather_evidence(ctx: Context, node_input: Candidate):
    admission = store.admission(node_input.candidate_id)
    if admission not in RUNNABLE:
        existing = store.find_incident_for_candidate(node_input.candidate_id) or {}
        yield _text(
            f"Candidate {node_input.candidate_id} {_NOT_RUN[admission]} "
            f"(incident {existing.get('incident_id')}, {existing.get('status')}); nothing to do."
        )
        yield Event(output={"status": admission}, route="stop")
        return
    incident_id = incident_id_for(node_input.candidate_id)
    opened = {
        "incident_id": incident_id,
        "candidate_id": node_input.candidate_id,
        "kind": node_input.kind,
        "session_id": ctx.session.id,
        "user_id": ctx.session.user_id,
    }
    try:
        found = evidence.load(
            node_input.candidate_id, used_by=f"incident:{incident_id}"
        )
    except Exception as e:
        # The incident must exist and be failed, or the push endpoint would acknowledge a delivery that never ran.
        store.begin_drafting(opened)
        store.mark_failed(incident_id, "gather_evidence", [f"{type(e).__name__}: {e}"])
        raise
    if found is None:
        yield _text(f"No evidence found for candidate {node_input.candidate_id}.")
        yield Event(output={"status": "no_evidence"}, route="stop")
        return
    incident = store.begin_drafting(
        {
            **opened,
            "product_id": found.product.product_id,
            "product_name": f"{found.product.brand} {found.product.name} {found.product.size}",
            "supplier_id": found.product.supplier_id,
            "supplier_name": found.product.supplier_name,
            "hazard_type": found.hazard_type,
        }
    )
    if admission != "new":
        store.append_audit(
            "desk",
            "redraft_incident",
            "incident",
            incident_id,
            before=incident["history"][-1],
            after={"attempt": incident["attempt"], "admission": admission},
        )
    dumped = found.model_dump(mode="json")
    yield Event(
        output=dumped,
        route="new",
        state={
            "evidence": dumped,
            "incident_id": incident_id,
            "validation_attempts": 0,
            "validation_error": "",
        },
    )


def end_run(node_input: Any) -> None:
    """Terminal node for runs that stop before an incident exists (not a candidate, already handled, no evidence)."""
    return None


def propose_actions(node_input: EvidencePack):
    incident_id = incident_id_for(node_input.candidate_id)
    try:
        proposed = actions.propose(node_input, policy.current())
    except (policy.PolicyUnavailable, ValueError) as e:
        store.mark_failed(incident_id, "propose_actions", [str(e)])
        raise
    store.update_incident(incident_id, severity=proposed.severity)
    # The proposal is visible in the trajectory, so the audit trail and the evaluation see where each id and figure on
    # the card comes from; state alone does not reach them.
    receipts = (
        f" Figures from receipt {', '.join(proposed.receipts)}."
        if proposed.receipts
        else ""
    )
    yield _text(
        f"Proposed by policy for {node_input.candidate_id} (severity {proposed.severity}):\n"
        + "\n".join(_action_lines(proposed, units_per_store=True))
        + receipts
    )
    yield Event(
        output=node_input.model_dump(mode="json"),
        state={"proposed": proposed.model_dump(mode="json")},
    )


def _skill_text(skill_dir: Path) -> tuple[str, list[str]]:
    """SKILL.md plus every reference and asset, and the concepts the generated files were rendered from.

    The drafter has no tools to fetch skill files, and they are short. HTML comments are for maintainers and are left
    out; a generated file's header names its source concepts, which the drafter has seen and so may cite.
    """
    skill = load_skill_from_dir(skill_dir)
    files = {
        **{f"references/{k}": v for k, v in skill.resources.references.items()},
        **{f"assets/{k}": v for k, v in skill.resources.assets.items()},
    }
    texts = {
        name: text for name, text in sorted(files.items()) if isinstance(text, str)
    }
    sources = sorted(
        {
            p
            for text in texts.values()
            for header in _GENERATED_FROM.findall(text)
            for p in _CONCEPT_PATH.findall(header)
        }
    )
    parts = [skill.instructions] + [
        f"## {name}\n\n{_HTML_COMMENT.sub('', text).strip()}"
        for name, text in texts.items()
    ]
    return "\n\n".join(parts), sources


def _figures_text(proposed: ProposedActions) -> str:
    """The figures the text may quote, totalled by code so the drafter never adds up rows itself."""
    parts = []
    if proposed.store_actions:
        verb = proposed.store_actions[0].action
        units = sum(a.qty_on_hand for a in proposed.store_actions)
        parts.append(
            f"{len(proposed.store_actions)} stores get a {verb}, holding {units} units on hand between them"
        )
    if proposed.optional_store_actions:
        units = sum(a.qty_on_hand for a in proposed.optional_store_actions)
        parts.append(
            f"{len(proposed.optional_store_actions)} exposed stores are optional pulls, holding {units} units on hand"
        )
    if proposed.message_orders:
        parts.append(f"{len(proposed.message_orders)} online orders are messaged")
    if not parts:
        return (
            "No store or order figures apply: this incident changes the listing only."
        )
    return "; ".join(parts) + f" (receipt {', '.join(proposed.receipts) or 'none'})."


def prepare_context(ctx: Context, node_input: EvidencePack) -> Event:
    pol = policy.current()
    skill_dir = SKILLS_DIR / f"{node_input.kind}-incident"
    store_ids = [a["store_id"] for a in ctx.state["proposed"]["store_actions"]] or [
        c.store_id for c in node_input.checks
    ]
    shown = knowledge.for_incident(
        playbook=pol.playbook(node_input.hazard_type),
        supplier_id=node_input.product.supplier_id,
        product_id=node_input.product.product_id,
        store_ids=store_ids,
    )
    skill_text, skill_sources = _skill_text(skill_dir)
    proposed = ProposedActions.model_validate(ctx.state["proposed"])
    observations, observations_timeout = memory.retrieve(
        store,
        memory.scopes_for(
            node_input.product.supplier_id, node_input.product.product_id, store_ids
        ),
        query=node_input.title_hint,
    )
    return Event(
        output=node_input.model_dump(mode="json"),
        state={
            "skill_instructions": skill_text,
            "policy_text": pol.as_text(node_input.kind),
            "knowledge_block": knowledge.render(shown),
            "observations_block": memory.render(observations),
            "observations_timeout": observations_timeout,
            "proposed_json": json.dumps(ctx.state["proposed"], indent=2),
            "figures_text": _figures_text(proposed),
            "knowledge_paths": list(
                dict.fromkeys(
                    [c.path for c in shown]
                    + policy.SHOWN_POLICY[node_input.kind]
                    + skill_sources
                    + [o.name for o in observations]
                )
            ),
            "knowledge_version": pol.version,
            "skill_version": knowledge.content_hash(skill_dir),
        },
    )


def route_by_kind(node_input: dict) -> Event:
    return Event(output=node_input, route=node_input["kind"])


def validate_and_persist(ctx: Context, node_input: dict | None) -> Event:
    evidence = EvidencePack.model_validate(ctx.state["evidence"])
    proposed = ProposedActions.model_validate(ctx.state["proposed"])
    incident_id = incident_id_for(evidence.candidate_id)
    screen = ctx.state.get(screening.SCREEN_KEY) or {}
    if screening.blocked(screen, "prompt"):
        # The same evidence is blocked every time, so the run ends without redrafting.
        store.mark_blocked(incident_id, screen, proposed.model_dump(mode="json"))
        return Event(
            output={"incident_id": incident_id, "status": "blocked"}, route="blocked"
        )
    if screening.blocked(screen, "response"):
        draft = None
        problems = [
            "Model Armor blocked it ("
            + (", ".join(screen["response"].get("filters") or []) or "no filter named")
            + ")"
        ]
    else:
        draft = IncidentText.model_validate(node_input)
        problems = inconsistencies(
            draft, evidence, proposed, ctx.state.get("knowledge_paths", [])
        )
    attempts = ctx.state.get("validation_attempts", 0)
    if problems and attempts < REDRAFT_ATTEMPTS:
        return Event(
            output=ctx.state["evidence"],
            route="retry",
            state={
                "validation_attempts": attempts + 1,
                "validation_error": "A previous draft was rejected because: "
                + "; ".join(problems)
                + ".",
                screening.SCREEN_KEY: {},
            },
        )
    if problems:
        store.mark_failed(incident_id, "validate_and_persist", problems)
        raise ValueError(
            f"Draft for {incident_id} is inconsistent with the evidence after retries: {problems}"
        )
    store.update_incident(
        incident_id,
        status="awaiting_approval",
        draft=draft.model_dump(mode="json"),
        proposed=proposed.model_dump(mode="json"),
        session_id=ctx.session.id,
        user_id=ctx.session.user_id,
        interrupt_id=f"approve:{incident_id}",
        redrafts=attempts,
        awaiting_approval_at=now(),
        knowledge_version=ctx.state.get("knowledge_version"),
        skill_version=ctx.state.get("skill_version"),
        screening=screen,
    )
    return Event(
        output={"incident_id": incident_id}, route="ok", state={"validation_error": ""}
    )


def _action_lines(
    proposed: ProposedActions, units_per_store: bool = False
) -> list[str]:
    def stores(store_actions) -> str:
        return ", ".join(
            f"{a.store_id} ({a.qty_on_hand})" if units_per_store else a.store_id
            for a in store_actions
        )

    lines = []
    if proposed.store_actions:
        verb = proposed.store_actions[0].action
        units = sum(a.qty_on_hand for a in proposed.store_actions)
        lines.append(
            f"- {verb} at {len(proposed.store_actions)} stores ({units} units on hand): {stores(proposed.store_actions)}"
        )
    if proposed.optional_store_actions:
        units = sum(a.qty_on_hand for a in proposed.optional_store_actions)
        lines.append(
            f"- no store action proposed; optional pulls (add_stores) at "
            f"{len(proposed.optional_store_actions)} exposed stores ({units} units on hand): "
            f"{stores(proposed.optional_store_actions)}"
        )
    if proposed.message_orders:
        lines.append(f"- message {len(proposed.message_orders)} online orders")
    lines.append(f"- checkout block: {'yes' if proposed.checkout_block else 'no'}")
    for fix in proposed.listing_fixes:
        lines.append(
            f"- listing fix on {fix.field}: add {fix.add or '-'}, remove {fix.remove or '-'}"
            + (f", set to {fix.set_to}" if fix.set_to else "")
        )
    if proposed.supplier_notice:
        lines.append("- supplier notice")
    if proposed.vendor_case:
        lines.append("- vendor case")
    return lines


def render_card(incident: dict) -> str:
    """The incident as the coordinator reads it: the draft and the proposal, or once approved, what was approved."""
    approved = incident.get("approved")
    draft = IncidentText.model_validate(
        approved["text"] if approved else incident["draft"]
    )
    proposed = ProposedActions.model_validate(
        approved["actions"] if approved else incident["proposed"]
    )
    lines = [
        executor.DEMO_NOTICE,
        "",
        f"**{draft.title}** (severity {proposed.severity})",
        "",
        draft.narrative,
        "",
        "Approved actions:" if approved else "Proposed actions:",
        *_action_lines(proposed),
    ]
    considerations = proposed.considerations + draft.considerations
    if considerations:
        lines += ["", "Considerations:", *[f"- {c}" for c in considerations]]
    lines += ["", "Evidence:", *[f"- {e}" for e in draft.evidence]]
    if draft.customer_message:
        lines += [
            "",
            f"Customer message: {draft.customer_message.subject}",
            draft.customer_message.body,
        ]
    if proposed.receipts:
        lines += ["", f"Attestation receipts: {', '.join(proposed.receipts)}"]
    return "\n".join(lines)


def await_approval(node_input: dict):
    incident = store.get_incident(node_input["incident_id"])
    yield _text(render_card(incident))
    yield RequestInput(
        interrupt_id=incident["interrupt_id"],
        message=(
            'Approve, edit or dismiss this incident. Reply {"decision": "approve"}, or {"decision": "dismiss", '
            '"reason": "..."}; edits go in add_stores (from the optional stores), remove_stores, pull_stores '
            "(hold becomes pull), checkout_block and text."
        ),
        payload={
            "incident_id": incident["incident_id"],
            "title": incident["draft"]["title"],
        },
        response_schema=Decision,
    )


def apply_decision(node_input: dict) -> Event:
    # Resume validation returns every schema field, with None for the ones the coordinator left out.
    decision = Decision.model_validate(
        {k: v for k, v in node_input.items() if v is not None}
    )
    dumped = decision.model_dump(mode="json")
    return Event(output=dumped, route=decision.decision, state={"decision": dumped})


def execute_approved(ctx: Context, node_input: Decision):
    result = executor.approve_incident(store, ctx.state["incident_id"], node_input)
    summary = (
        f"Approved by {node_input.actor}. {result['open_tasks']} store tasks issued, "
        f"{result.get('customer_messages', 0)} customer messages sent."
    )
    if result.get("notes"):
        summary += " " + " ".join(result["notes"])
    yield _text(summary)
    yield Event(output=result, route="verify" if result["open_tasks"] else "closed")


def close_dismissed(ctx: Context, node_input: Decision):
    result = executor.dismiss_incident(store, ctx.state["incident_id"], node_input)
    incident = store.get_incident(ctx.state["incident_id"])
    learn.revoke(store, incident)
    learn.remember(
        store, incident, result.get("memory_facts") or [], "dismissed_incident"
    )
    yield _text(
        f"Dismissed by {node_input.actor}: {node_input.reason or 'no reason given'}. {result['status']}."
    )


@node(rerun_on_resume=True)
def await_verification(ctx: Context, node_input: Any):
    """Pauses once for every open store task at the same time, so stores verify in any order, and reruns on each verdict.

    A rerun sees every verdict given so far, and recording one again changes nothing, so only new verdicts are written. A
    not-clear or retake verdict issues the task again under a new id, which gets a pause of its own.
    """
    for interrupt_id, reply in sorted((ctx.resume_inputs or {}).items()):
        if not interrupt_id.startswith("verify:"):
            continue
        task_id = interrupt_id.removeprefix("verify:")
        verdict = ShelfVerdict.model_validate(reply)
        result = executor.record_verification(store, task_id, verdict)
        if result.get("already_recorded"):
            continue
        reissued = (
            f" Reissued as {result['reissued_task_id']}."
            if result.get("reissued_task_id")
            else ""
        )
        yield _text(f"Recorded {verdict.verdict} for {task_id}.{reissued}")
    open_tasks = store.open_tasks(ctx.state["incident_id"])
    if not open_tasks:
        yield Event(output={"incident_id": ctx.state["incident_id"]})
        return
    asked = set(ctx.state.get("verification_asked") or [])
    for task in open_tasks:
        if task["task_id"] not in asked:
            yield _text(
                f"Shelf check: {task['kind']} {task['code']} at store {task['store_id']}"
                + (f", aisle {task['aisle']}" if task.get("aisle") else "")
                + "."
            )
    yield Event(
        state={"verification_asked": sorted(asked | {t["task_id"] for t in open_tasks})}
    )
    for task in open_tasks:
        yield RequestInput(
            interrupt_id=f"verify:{task['task_id']}",
            message='Reply {"verdict": "verified_clear"}, {"verdict": "not_clear"} or {"verdict": "retake"}.',
            payload={
                "task_id": task["task_id"],
                "store_id": task["store_id"],
                "code": task["code"],
            },
            response_schema=ShelfVerdict,
        )


def close_and_learn(ctx: Context, node_input: Any):
    result = executor.close_incident(store, ctx.state["incident_id"])
    learn.remember(
        store,
        store.get_incident(ctx.state["incident_id"]),
        result["memory_facts"],
        "approved_incident",
    )
    yield _text(f"Incident {ctx.state['incident_id']} closed.")
